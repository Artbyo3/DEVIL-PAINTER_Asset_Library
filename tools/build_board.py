"""Generate the Markdown image board under board/ from packs.json and committed thumbs/.

Usage:
    python tools/build_board.py [--catalog packs.json] [--board-dir board] [--thumbs-dir thumbs]

Generates:
  - board/README.md: index of all packs with a cover thumbnail each
  - board/<pack-slug>.md: per-pack 4-column image grid of committed WebP thumbs,
    each linking to (a) the pack's shelf draft release page and (b) the public file.

All files under board/ are generated artifacts and must never be hand-edited.
"""

from __future__ import annotations

import argparse
import json
import os
import tempfile
from pathlib import Path
from typing import Any
from urllib.parse import quote

try:
    import build_pack_entry
    import make_pack
    import vt_scan_gate
except ImportError:
    from tools import build_pack_entry, make_pack, vt_scan_gate  # type: ignore[no-redef]

DEFAULT_REPO = build_pack_entry.DEFAULT_REPO
GRID_COLUMNS = 4
GENERATED_HEADER = "<!-- AUTO-GENERATED by tools/build_board.py — DO NOT HAND-EDIT -->"


def _atomic_write_text(target_path: Path, text: str) -> None:
    if target_path.is_symlink():
        raise ValueError(f"Refusing to write through symlink: {target_path}")
    target_path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{target_path.name}.", suffix=".tmp", dir=str(target_path.parent)
    )
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        os.replace(tmp_path, target_path)
    except Exception:
        if tmp_path.exists():
            tmp_path.unlink()
        raise


def _escape_md(text: str) -> str:
    return (
        str(text)
        .replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("[", "\\[")
        .replace("]", "\\]")
        .replace("\r", " ")
        .replace("\n", " ")
    )


def fetch_shelf_urls(repo: str, gh_token: str) -> dict[str, str]:
    """Query GitHub draft releases tagged shelf-<slug> and return slug -> html_url."""
    build_pack_entry.validate_repo(repo)
    if not gh_token:
        return {}
    urls: dict[str, str] = {}
    page = 1
    while True:
        api_url = f"https://api.github.com/repos/{repo}/releases?per_page=100&page={page}"
        _, body, _ = vt_scan_gate.gh_api_request(api_url, gh_token)
        items = json.loads(body.decode("utf-8"))
        if not items:
            break
        for rel in items:
            if not isinstance(rel, dict):
                continue
            tag = str(rel.get("tag_name", ""))
            if rel.get("draft") is True and tag.startswith("shelf-") and len(tag) > len("shelf-"):
                slug = tag[len("shelf-") :]
                html_url = str(rel.get("html_url", "")).strip()
                if html_url:
                    urls[slug] = html_url
        page += 1
    return urls


def _default_shelf_url(repo: str, slug: str) -> str:
    return f"https://github.com/{repo}/releases/tag/{quote(f'shelf-{slug}', safe='')}"


def _public_release_url(repo: str, release_tag: str) -> str:
    return f"https://github.com/{repo}/releases/tag/{quote(release_tag, safe='')}"


def _public_file_url(repo: str, release_tag: str, filename: str) -> str:
    return (
        f"https://github.com/{repo}/releases/download/"
        f"{quote(release_tag, safe='')}/{quote(filename, safe='')}"
    )


def _thumb_rel_from_board(thumb_path_str: str) -> str:
    cleaned = thumb_path_str.lstrip("/").replace("\\", "/")
    if ".." in cleaned.split("/"):
        raise ValueError(f"Unsafe thumb path: {thumb_path_str!r}")
    return f"../{cleaned}"


def _resolve_cover_thumb(pack: dict[str, Any]) -> str | None:
    thumbs = pack.get("thumbs")
    if not isinstance(thumbs, dict) or not thumbs:
        return None
    files = pack.get("files") or []
    for fname in files:
        if fname in thumbs and isinstance(thumbs[fname], str):
            return thumbs[fname]
    for val in thumbs.values():
        if isinstance(val, str):
            return val
    return None


def _render_pack_board(
    pack: dict[str, Any],
    slug: str,
    shelf_url: str,
    repo: str,
) -> str:
    name = str(pack.get("name", slug))
    desc = str(pack.get("description", "")).strip()
    size_str = str(pack.get("size", "")).strip()
    release_tag = build_pack_entry.validate_release_tag(str(pack["releaseTag"]))
    download_url = str(pack.get("downloadUrl", "")).strip()
    files = [build_pack_entry.validate_safe_filename(str(f)) for f in pack.get("files", [])]
    thumbs: dict[str, str] = pack.get("thumbs") if isinstance(pack.get("thumbs"), dict) else {}
    tags = [str(t) for t in pack.get("tags", [])]

    pub_rel_url = _public_release_url(repo, release_tag)
    lines: list[str] = [
        GENERATED_HEADER,
        "",
        f"# {_escape_md(name)}",
        "",
        f"[All Packs](README.md) · [Shelf Draft (`shelf-{slug}`)]({shelf_url}) · "
        f"[Public Release (`{release_tag}`)]({pub_rel_url})"
        + (f" · [Download Zip]({download_url})" if download_url else ""),
        "",
    ]
    if desc:
        lines.append(desc)
        lines.append("")
    meta_bits = [f"**Files:** {len(files)}"]
    if size_str:
        meta_bits.append(f"**Zip Size:** {size_str}")
    if tags:
        meta_bits.append("**Tags:** " + ", ".join(f"`{t}`" for t in tags))
    lines.append(" · ".join(meta_bits))
    lines.append("")

    if not files:
        lines.append("_No files in this pack._")
        lines.append("")
        return "\n".join(lines)

    lines.append(
        "| " + " | ".join(f"Asset {i + 1}" for i in range(GRID_COLUMNS)) + " |"
    )
    lines.append("| " + " | ".join(":---:" for _ in range(GRID_COLUMNS)) + " |")

    cells: list[str] = []
    for fname in files:
        pub_file = _public_file_url(repo, release_tag, fname)
        thumb_rel = thumbs.get(fname)
        escaped_name = _escape_md(fname)
        if isinstance(thumb_rel, str) and thumb_rel.strip():
            rel_img = _thumb_rel_from_board(thumb_rel)
            img_link = f"[![{escaped_name}]({rel_img})]({shelf_url})"
        else:
            img_link = f"[{escaped_name}]({shelf_url})"
        cell = f"{img_link}<br>`{escaped_name}`<br>[Shelf]({shelf_url}) · [Public]({pub_file})"
        cells.append(cell)

    for idx in range(0, len(cells), GRID_COLUMNS):
        row = cells[idx : idx + GRID_COLUMNS]
        while len(row) < GRID_COLUMNS:
            row.append("")
        lines.append("| " + " | ".join(row) + " |")

    lines.append("")
    return "\n".join(lines)


def _render_index_board(
    pack_records: list[tuple[dict[str, Any], str, str]],
    repo: str,
) -> str:
    total_files = sum(len(p.get("files", [])) for p, _, _ in pack_records)
    lines: list[str] = [
        GENERATED_HEADER,
        "",
        "# Library Management Board",
        "",
        f"Visual index of **{len(pack_records)}** pack(s) (**{total_files}** assets total). "
        "Generated from [`packs.json`](../packs.json) and committed [`thumbs/`](../thumbs).",
        "",
    ]

    if not pack_records:
        lines.append("_No packs currently published in `packs.json`._")
        lines.append("")
        return "\n".join(lines)

    lines.extend(
        [
            "| Cover | Pack | Files | Size | Links |",
            "| :---: | :--- | :---: | :---: | :--- |",
        ]
    )

    for pack, slug, shelf_url in pack_records:
        name = str(pack.get("name", slug))
        desc = _escape_md(str(pack.get("description", "")).strip())
        size_str = _escape_md(str(pack.get("size", "")).strip())
        files_count = len(pack.get("files", []))
        release_tag = build_pack_entry.validate_release_tag(str(pack["releaseTag"]))
        pub_rel_url = _public_release_url(repo, release_tag)
        pack_board = f"{slug}.md"

        cover_rel = _resolve_cover_thumb(pack)
        if cover_rel:
            rel_img = _thumb_rel_from_board(cover_rel)
            cover_cell = f"[![{_escape_md(name)}]({rel_img})]({pack_board})"
        else:
            cover_cell = f"[Open]({pack_board})"

        pack_cell = f"**[{_escape_md(name)}]({pack_board})**"
        if desc:
            pack_cell += f"<br>{desc}"
        links_cell = f"[Grid]({pack_board}) · [Shelf (`shelf-{slug}`)]({shelf_url}) · [Public]({pub_rel_url})"
        lines.append(
            f"| {cover_cell} | {pack_cell} | {files_count} | {size_str} | {links_cell} |"
        )

    lines.append("")
    return "\n".join(lines)


def build_board(
    catalog_path: Path = Path("packs.json"),
    board_dir: Path = Path("board"),
    thumbs_dir: Path = Path("thumbs"),
    repo: str = DEFAULT_REPO,
    shelf_urls: dict[str, str] | None = None,
) -> list[Path]:
    build_pack_entry.validate_repo(repo)
    if catalog_path.is_symlink():
        raise ValueError(f"Refusing to read symlink catalog: {catalog_path}")
    if board_dir.is_symlink():
        raise ValueError(f"Refusing to write to symlink board dir: {board_dir}")
    if thumbs_dir.is_symlink():
        raise ValueError(f"Symlink thumbs dir is not allowed: {thumbs_dir}")

    data = json.loads(catalog_path.read_text(encoding="utf-8"))
    packs = data.get("packs")
    if not isinstance(packs, list):
        raise ValueError(f"Expected 'packs' list in {catalog_path}")

    resolved_urls = dict(shelf_urls or {})
    board_dir.mkdir(parents=True, exist_ok=True)
    board_root = board_dir.resolve()

    pack_records: list[tuple[dict[str, Any], str, str]] = []
    seen_slugs: set[str] = set()
    written_files: list[Path] = []

    for pack in packs:
        if not isinstance(pack, dict):
            continue
        name = str(pack.get("name", "")).strip()
        slug = make_pack.slugify_pack_name(name)
        if not slug:
            raise ValueError(f"Could not derive slug for pack {name!r}")
        if slug in seen_slugs:
            raise ValueError(f"Duplicate pack slug in catalog: {slug!r}")
        seen_slugs.add(slug)

        shelf_url = resolved_urls.get(slug) or _default_shelf_url(repo, slug)
        pack_records.append((pack, slug, shelf_url))

        pack_md = (board_root / f"{slug}.md").resolve()
        if pack_md.parent != board_root:
            raise ValueError(f"Pack board path escapes board dir: {pack_md}")
        _atomic_write_text(pack_md, _render_pack_board(pack, slug, shelf_url, repo))
        written_files.append(pack_md)

    index_md = (board_root / "README.md").resolve()
    _atomic_write_text(index_md, _render_index_board(pack_records, repo))
    written_files.append(index_md)

    expected_names = {p.name for p in written_files}
    for existing in sorted(board_root.iterdir(), key=lambda p: p.name):
        if existing.is_symlink():
            raise ValueError(f"Symlink entry inside board dir is not allowed: {existing}")
        if existing.is_file() and existing.suffix.lower() == ".md" and existing.name not in expected_names:
            existing.unlink()

    return written_files


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate board/ Markdown grids from packs.json.")
    parser.add_argument("--catalog", type=Path, default=Path("packs.json"))
    parser.add_argument("--board-dir", type=Path, default=Path("board"))
    parser.add_argument("--thumbs-dir", type=Path, default=Path("thumbs"))
    parser.add_argument("--repo", default=DEFAULT_REPO)
    parser.add_argument(
        "--shelf-urls-json",
        type=Path,
        default=None,
        help="Optional JSON file mapping <pack-slug> to shelf release html_url",
    )
    args = parser.parse_args(argv)

    shelf_urls: dict[str, str] = {}
    if args.shelf_urls_json is not None and args.shelf_urls_json.is_file():
        shelf_urls = json.loads(args.shelf_urls_json.read_text(encoding="utf-8"))
    elif os.environ.get("GH_TOKEN", "").strip():
        try:
            shelf_urls = fetch_shelf_urls(args.repo, os.environ["GH_TOKEN"].strip())
        except Exception as exc:
            print(f"WARNING: Could not fetch shelf draft URLs ({exc}); using tag fallback URLs.")

    written = build_board(
        catalog_path=args.catalog,
        board_dir=args.board_dir,
        thumbs_dir=args.thumbs_dir,
        repo=args.repo,
        shelf_urls=shelf_urls,
    )
    print(f"Generated {len(written)} board file(s) in {args.board_dir}/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
