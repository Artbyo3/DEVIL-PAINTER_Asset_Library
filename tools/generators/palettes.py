def _parse_hex_color(token: str) -> tuple[int, int, int]:
    s = token.strip().lstrip("#")
    if len(s) == 3:
        s = "".join(ch * 2 for ch in s)
    if len(s) != 6:
        raise ValueError(f"Invalid hex color: {token!r}")
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16))


def _resample_5_stops(stops: Sequence[Sequence[int]]) -> list[tuple[int, int, int]]:
    pts = [(int(c[0]), int(c[1]), int(c[2])) for c in stops]
    if len(pts) == 5:
        return pts
    if len(pts) == 1:
        return pts * 5
    if len(pts) < 1:
        raise ValueError("Palette must contain at least 1 RGB stop")
    xs = np.linspace(0.0, 1.0, len(pts))
    tx = np.linspace(0.0, 1.0, 5)
    r = np.interp(tx, xs, [p[0] for p in pts])
    g = np.interp(tx, xs, [p[1] for p in pts])
    b = np.interp(tx, xs, [p[2] for p in pts])
    return [(int(round(r[i])), int(round(g[i])), int(round(b[i]))) for i in range(5)]


def resolve_palette(
    palette: str | Sequence[str] | Sequence[Sequence[int]] | None,
    default_palette: str,
    rng: np.random.Generator | None = None,
) -> list[tuple[int, int, int]]:
    if palette is None:
        key = default_palette.lower().replace("-", "_")
        if key in PALETTES:
            return PALETTES[key]
        return PALETTES[PALETTE_NAMES[0]]

    if isinstance(palette, str):
        raw = palette.strip()
        if not raw:
            return resolve_palette(None, default_palette, rng)
        if raw.lower() == "auto":
            if rng is not None:
                return PALETTES[PALETTE_NAMES[int(rng.integers(0, len(PALETTE_NAMES)))]]
            return PALETTES[default_palette.lower().replace("-", "_")]
        if "," in raw or raw.startswith("#"):
            colors = [_parse_hex_color(part) for part in raw.split(",") if part.strip()]
            return _resample_5_stops(colors)
        key = raw.lower().replace("-", "_").replace(" ", "_")
        if key in PALETTES:
            return PALETTES[key]
        raise KeyError(f"Unknown palette {palette!r}. Use --list-palettes or pass comma-separated hex stops.")

    items = list(palette)
    if not items:
        return resolve_palette(None, default_palette, rng)
    if isinstance(items[0], str):
        return _resample_5_stops([_parse_hex_color(str(s)) for s in items])
    return _resample_5_stops(items)  # type: ignore[arg-type]
